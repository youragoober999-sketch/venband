-- =============================================================================
-- Make the column-level grants authoritative (20261106080000)
--
-- Venband limits which columns signed-in users can read or write with column
-- grants (bot token hashes are never readable; on profiles you can only edit
-- your own display fields, …). But some Supabase projects grant ALL on every
-- table to `authenticated` by default, and a table-wide grant overrides the
-- column limits — e.g. anyone who could see a bot could read its token_hash.
-- For each table + privilege the migrations only grant on some columns, revoke
-- the table-wide privilege and grant exactly those columns (generated by
-- scripts/column-grants.mjs). Also grants applications.banner_url, which the
-- app reads and sets but no migration granted.
--
-- On projects without the broad default this changes nothing. Safe to run more
-- than once.
-- =============================================================================

revoke select on public.applications from authenticated;
grant select (id, owner_id, name, description, preset, icon_url, banner_url, color, token_hint, status, created_at, updated_at, tags, script) on public.applications to authenticated;
revoke update on public.applications from authenticated;
grant update (name, description, icon_url, banner_url, color, tags, script) on public.applications to authenticated;
revoke select on public.bot_commands from authenticated;
grant select (app_id, name, description, response) on public.bot_commands to authenticated;
revoke update on public.channels from authenticated;
grant update (name, topic, category, position, is_private, settings, color) on public.channels to authenticated;
revoke update on public.invites from authenticated;
grant update (paused, label) on public.invites to authenticated;
revoke update on public.memories from authenticated;
grant update (caption, active, expires_at, audience) on public.memories to authenticated;
revoke update on public.messages from authenticated;
grant update (epoch, iv, ciphertext, signature, author_key_id) on public.messages to authenticated;
revoke update on public.notifications from authenticated;
grant update (read_at) on public.notifications to authenticated;
revoke update on public.polls from authenticated;
grant update (expires_at) on public.polls to authenticated;
revoke update on public.profiles from authenticated;
grant update (display_name, avatar_color, about, pronouns, status_text, status_emoji, presence, banner_color, banner_color2, accent_color, nameplate, language, onboarded, avatar_url, banner_url, avatar_frame, name_style, nameplate_style, profile_effect) on public.profiles to authenticated;
revoke select on public.server_bots from authenticated;
grant select (id, server_id, app_id, added_by, settings, webhook_channel, created_at) on public.server_bots to authenticated;
revoke update on public.server_members from authenticated;
grant update (nickname) on public.server_members to authenticated;
revoke update on public.threads from authenticated;
grant update (name, locked, archived, tags, pinned, solved) on public.threads to authenticated;

notify pgrst, 'reload schema';
